def main() -> int:
    if not DB.exists():
        print(f"找不到数据库：{DB}")
        return 1

    conn = sqlite3.connect(DB)
    try:
        before = conn.execute("SELECT COUNT(*) FROM kb_items").fetchone()[0]
        # 全量替换本批数据：标题改过名也能清掉旧行，不会留重复
        conn.execute("DELETE FROM kb_items WHERE origin='qq_group'")
        added = updated = 0
        now = datetime.now().strftime("%Y-%m-%d %H:%M")
        for it in ITEMS:
            title = PREFIX + it["title"]
            exists = conn.execute(
                "SELECT id FROM kb_items WHERE origin='qq_group' AND title=?", (title,)
            ).fetchone()
            conn.execute(
                "INSERT INTO kb_items"
                " (title, keywords, answer, source, detail, fetched_at, verified_by_user, raw_excerpt, origin)"
                " VALUES (?, ?, ?, ?, ?, ?, 1, ?, 'qq_group')"
                " ON CONFLICT(origin, title) DO UPDATE SET"
                "   keywords=excluded.keywords, answer=excluded.answer, source=excluded.source,"
                "   detail=excluded.detail, fetched_at=excluded.fetched_at,"
                "   verified_by_user=1, raw_excerpt=excluded.raw_excerpt",
                (
                    title,
                    it["keywords"],
                    it["answer"],
                    it["source"],
                    it["detail"],
                    f"{it['date']} 00:00" if it["date"] else now,
                    it["excerpt"],
                ),
            )
            if exists:
                updated += 1
            else:
                added += 1
        conn.execute("INSERT INTO faq_fts(faq_fts) VALUES('rebuild')")
        conn.commit()
        after = conn.execute("SELECT COUNT(*) FROM kb_items").fetchone()[0]
        qq = conn.execute("SELECT COUNT(*) FROM kb_items WHERE origin='qq_group'").fetchone()[0]
    finally:
        conn.close()

    print(f"导入完成：新增 {added} 条，更新 {updated} 条")
    print(f"kb_items 总数 {before} → {after}，其中 qq_group {qq} 条")
    return 0


if __name__ == "__main__":
    sys.exit(main())
